"""Static contract tests for the OpenClaw adapter (openclaw-plugin/).

Self-contained unittest using only the Python standard library. No
Node.js, npm, or OpenClaw CLI installation is required.

These tests validate the static file/manifest contracts that OpenClaw
reads *before* loading plugin runtime code:

  - openclaw.plugin.json exists, is valid JSON, and has the required
    fields (id, configSchema, contracts.tools, activation).
  - contracts.tools matches the tool names declared in src/index.ts.
  - package.json has openclaw extensions metadata and typebox dep.
  - src/index.ts uses defineToolPlugin and declares the expected tools.
  - README documents install and validation commands.
  - All files follow the Adjacent writing conventions (no em-dash, no
    emoji, mid-quote convention present, % not pp).

Run: python3 -m unittest tests.openclaw.test_openclaw -v
"""

import json
import os
import re
import unittest

from tests.adapters._helpers import assert_no_em_dash, assert_no_emoji

# Resolve the openclaw-plugin root from this file's location:
#   tests/openclaw/test_openclaw.py -> openclaw-plugin is two parents up
#   then into openclaw-plugin/.
_PLUGIN_ROOT = os.path.normpath(
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
)
OPENCLAW_DIR = os.path.join(_PLUGIN_ROOT, "openclaw-plugin")

# Expected tool names - must match contracts.tools in the manifest and
# the tool() declarations in src/index.ts.
EXPECTED_TOOLS = [
    "adjacent_doctor",
    "adjacent_brief",
    "adjacent_snapshot",
    "adjacent_chart",
    "adjacent_movers",
    "adjacent_capabilities",
    "adjacent_mcp_query",
    "adjacent_topic_brief",
    "adjacent_news_latest",
    "adjacent_news_correlation",
    "adjacent_correlation_regime",
    "adjacent_portfolio_snapshot",
    "adjacent_tracking",
    "adjacent_tracking_table",
    "adjacent_chart_csv",
    "adjacent_candles_chart",
    "adjacent_similar_hedges",
    "adjacent_snapshot_health",
    "adjacent_datawrapper_index",
    "adjacent_http_get",
    "adjacent_rebalance_plan",
]

# The shared Python core bundled into the tarball so a clean install needs
# no repo checkout.
BUNDLED_DIRS = ["scripts", "data", "skills"]

# Keywords that would indicate a trading or shell-execution capability -
# forbidden in a read-only plugin.
FORBIDDEN_KEYWORDS = ["execute order", "shell exec", "subprocess", "spawn"]


def _read(rel_path: str) -> str:
    full = os.path.join(OPENCLAW_DIR, rel_path)
    with open(full, "r", encoding="utf-8") as fh:
        return fh.read()


def _file_exists(rel_path: str) -> bool:
    return os.path.isfile(os.path.join(OPENCLAW_DIR, rel_path))


class TestManifest(unittest.TestCase):
    """Validate openclaw.plugin.json structure and required fields."""

    def test_manifest_exists(self):
        self.assertTrue(
            _file_exists("openclaw.plugin.json"),
            "openclaw.plugin.json is missing from the plugin root",
        )

    def test_manifest_is_valid_json(self):
        data = json.loads(_read("openclaw.plugin.json"))
        self.assertIsInstance(data, dict)

    def test_manifest_has_id(self):
        data = json.loads(_read("openclaw.plugin.json"))
        self.assertEqual(data.get("id"), "adjacent-markets")

    def test_manifest_has_name_and_description(self):
        data = json.loads(_read("openclaw.plugin.json"))
        self.assertTrue(data.get("name"), "manifest missing name")
        self.assertTrue(data.get("description"), "manifest missing description")

    def test_manifest_has_config_schema(self):
        data = json.loads(_read("openclaw.plugin.json"))
        schema = data.get("configSchema")
        self.assertIsInstance(schema, dict)
        self.assertEqual(schema.get("type"), "object")
        # The manifest is generated by `openclaw plugins build`; it exposes
        # apiKey and tier and omits additionalProperties by design.
        self.assertIn("apiKey", schema.get("properties", {}))
        self.assertIn("tier", schema.get("properties", {}))

    def test_manifest_has_contracts_tools(self):
        data = json.loads(_read("openclaw.plugin.json"))
        tools = data.get("contracts", {}).get("tools", [])
        self.assertIsInstance(tools, list)
        self.assertEqual(
            sorted(tools),
            sorted(EXPECTED_TOOLS),
            "contracts.tools does not match expected tool names",
        )

    def test_manifest_has_activation(self):
        data = json.loads(_read("openclaw.plugin.json"))
        activation = data.get("activation", {})
        self.assertIsInstance(activation, dict)
        self.assertIn("onStartup", activation)

    def test_manifest_has_mcp_servers(self):
        data = json.loads(_read("openclaw.plugin.json"))
        servers = data.get("mcpServers", {})
        self.assertIn("adjacent-markets", servers)
        self.assertIn("adjacent-markets-dev", servers)

    def test_manifest_no_em_dash_or_emoji(self):
        text = _read("openclaw.plugin.json")
        self.assertEqual(assert_no_em_dash(text), [], "manifest has em-dash")
        self.assertEqual(assert_no_emoji(text), [], "manifest has emoji")

    def test_manifest_description_mentions_readonly(self):
        text = _read("openclaw.plugin.json").lower()
        self.assertIn("read-only", text)


