class TestEntrypoint(unittest.TestCase):
    """Validate src/index.ts uses defineToolPlugin and declares the expected tools."""

    def test_entrypoint_exists(self):
        self.assertTrue(_file_exists("src/index.ts"))

    def test_uses_define_tool_plugin(self):
        text = _read("src/index.ts")
        self.assertIn(
            "defineToolPlugin",
            text,
            "entrypoint must use defineToolPlugin from openclaw/plugin-sdk/tool-plugin",
        )
        self.assertIn(
            "openclaw/plugin-sdk/tool-plugin",
            text,
            "entrypoint must import from openclaw/plugin-sdk/tool-plugin",
        )

    def test_uses_typebox(self):
        text = _read("src/index.ts")
        self.assertIn('from "typebox"', text)
        self.assertIn("Type.Object", text)

    def test_declares_expected_tools(self):
        text = _read("src/index.ts")
        for tool_name in EXPECTED_TOOLS:
            with self.subTest(tool=tool_name):
                self.assertIn(
                    'name: "%s"' % tool_name,
                    text,
                    "entrypoint does not declare tool %s" % tool_name,
                )

    def test_plugin_id_matches_manifest(self):
        text = _read("src/index.ts")
        self.assertIn('id: "adjacent-markets"', text)

    def test_no_order_placement(self):
        text = _read("src/index.ts").lower()
        for bad in FORBIDDEN_KEYWORDS:
            with self.subTest(keyword=bad):
                self.assertNotIn(
                    bad,
                    text,
                    "entrypoint contains forbidden keyword: %s" % bad,
                )

    def test_mid_quote_convention_present(self):
        text = _read("src/index.ts").lower()
        self.assertIn("mid", text, "entrypoint must reference mid-quote convention")

    def test_no_pp_unit(self):
        """The entrypoint must not use 'pp' as a unit (only %)."""
        text = _read("src/index.ts")
        # 'pp' as a standalone unit token is banned. We check for common
        # patterns but allow 'pp' inside identifiers like 'app' or 'happens'.
        # The banned usage is as a unit: e.g. "in pp" or "unit: pp".
        for pattern in (r'unit["\']?\s*[:=]\s*["\']pp', r'in\s+pp\b', r'\bpp\b\s*$'):
            matches = re.findall(pattern, text, re.MULTILINE)
            self.assertEqual(
                matches,
                [],
                "entrypoint uses banned 'pp' unit: %s" % matches,
            )

    def test_no_em_dash_or_emoji(self):
        text = _read("src/index.ts")
        self.assertEqual(assert_no_em_dash(text), [], "src/index.ts has em-dash")
        self.assertEqual(assert_no_emoji(text), [], "src/index.ts has emoji")

    def test_default_export_present(self):
        text = _read("src/index.ts")
        self.assertIn("export default", text)

    def test_no_shell_or_subprocess_import(self):
        text = _read("src/index.ts")
        for bad in ("child_process", "execSync", "spawn", "exec("):
            with self.subTest(token=bad):
                self.assertNotIn(
                    bad,
                    text,
                    "entrypoint must not import or use shell execution: %s" % bad,
                )


